export const products: Product[] = seeds.map(({ photos, ...p }, i) => ({
  ...p,
  id: i + 1,
  images: photos.map((id) => img(id, 800)),
}));

export const finalPrice = (p: Pick<Product, "price" | "discount">) =>
  Math.round((p.price * (100 - p.discount)) / 100 / 1000) * 1000;

export const getProduct = (slug: string) => products.find((p) => p.slug === slug);
export const byCategory = (slug: string) => products.filter((p) => p.category === slug);
export const amazingProducts = products.filter((p) => p.amazing);
export const bestSellers = [...products].sort((a, b) => b.reviews - a.reviews).slice(0, 12);
export const topRated = [...products].sort((a, b) => b.rating - a.rating).slice(0, 10);

export function searchProducts(q: string) {
  const term = q.trim().toLowerCase();
  if (!term) return [];
  return products.filter(
    (p) =>
      p.title.toLowerCase().includes(term) ||
      p.enTitle.toLowerCase().includes(term) ||
      p.brand.includes(term),
  );
}
